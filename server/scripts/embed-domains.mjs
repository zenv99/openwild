// Regenerates server/src/domainData.js from the text snapshots.
// Run from the repo root: node server/scripts/embed-domains.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const domains = fs.readFileSync(path.join(root, 'data/academic-domains.txt'), 'utf8')
const abused = fs.readFileSync(path.join(root, 'data/academic-domains-abused.txt'), 'utf8')
const out = `// Generated by server/scripts/embed-domains.mjs. Do not edit by hand.
// The text files in server/data are the source. Licenses: server/data/SOURCES.md
export const DOMAIN_TEXT = ${JSON.stringify(domains)}
export const ABUSED_TEXT = ${JSON.stringify(abused)}
`
fs.writeFileSync(path.join(root, 'src/domainData.js'), out)
console.log('wrote server/src/domainData.js', out.length, 'bytes')
